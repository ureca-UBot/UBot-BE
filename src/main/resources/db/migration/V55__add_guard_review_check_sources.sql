-- V53·V54의 가드 전 응답 수집에 검사 출처별 이력을 추가합니다.
-- 과거 기록의 출처는 추측해서 채우지 않습니다. 기존 테이블/데이터/마이그레이션은 보존합니다.
CREATE TABLE guard_review_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_key UUID NOT NULL UNIQUE,
    attempt_id BIGINT REFERENCES answer_attempts_history(attempt_id) ON DELETE SET NULL,
    origin VARCHAR(16) NOT NULL CHECK (origin IN ('INPUT_CODE','INPUT_LLM','OUTPUT_CODE','OUTPUT_LLM','UNKNOWN')),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('PASS','FILTERED','REJECTED','REVIEW','ERROR','SKIPPED','UNKNOWN')),
    reason_codes JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(reason_codes)='array'),
    question_snapshot TEXT,
    answer_snapshot TEXT,
    final_answer_snapshot TEXT,
    explanation TEXT,
    context_snapshot JSONB,
    details_retained BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    CHECK (origin NOT LIKE 'INPUT_%' OR (answer_snapshot IS NULL AND final_answer_snapshot IS NULL)),
    CHECK (outcome NOT IN ('REJECTED','REVIEW','ERROR') OR final_answer_snapshot IS NULL)
);
CREATE INDEX idx_guard_review_checks_filter ON guard_review_checks(origin,outcome,id DESC);
CREATE INDEX idx_guard_review_checks_attempt ON guard_review_checks(attempt_id,origin);

ALTER TABLE guard_review_items
    ADD COLUMN check_id BIGINT REFERENCES guard_review_checks(id) ON DELETE SET NULL,
    ADD COLUMN guard_origin VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
    ADD COLUMN guard_context JSONB;
ALTER TABLE guard_review_findings
    ADD COLUMN guard_origin VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
    ADD COLUMN guard_outcome VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN';
CREATE INDEX idx_guard_review_findings_origin ON guard_review_findings(guard_origin,guard_outcome,candidate_id);
