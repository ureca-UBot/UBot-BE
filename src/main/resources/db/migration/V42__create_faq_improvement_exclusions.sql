CREATE TABLE faq_improvement_exclusion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faq_id           BIGINT       NOT NULL REFERENCES faq (id) ON DELETE CASCADE,
    improvement_type VARCHAR(30)  NOT NULL CHECK (improvement_type IN (
        'LOW_RAG_QUALITY',
        'DUPLICATE_SUSPECTED',
        'LOW_USAGE'
    )),
    faq_version      INTEGER      NOT NULL,
    memo             VARCHAR(500),
    excluded_by      BIGINT       REFERENCES users (user_id) ON DELETE SET NULL,
    excluded_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_by      BIGINT       REFERENCES users (user_id) ON DELETE SET NULL,
    released_at      TIMESTAMP,
    CHECK (released_by IS NULL OR released_at IS NOT NULL)
);

CREATE UNIQUE INDEX uq_faq_improvement_exclusion_active
    ON faq_improvement_exclusion (faq_id, improvement_type, faq_version)
    WHERE released_at IS NULL;
