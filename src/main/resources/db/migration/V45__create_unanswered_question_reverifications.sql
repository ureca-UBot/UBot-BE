ALTER TABLE outbox_events
    DROP CONSTRAINT outbox_events_event_type_check,
    ADD CONSTRAINT outbox_events_event_type_check CHECK (event_type IN ('UNANSWERED_QUESTION', 'FAQ_REVERIFY'));

CREATE TABLE unanswered_question_reverifications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id       BIGINT           NOT NULL REFERENCES unanswered_questions (id) ON DELETE CASCADE,
    faq_id            BIGINT           NOT NULL REFERENCES faq (id) ON DELETE CASCADE,
    before_similarity DOUBLE PRECISION,
    after_similarity  DOUBLE PRECISION NOT NULL,
    created_at        TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_unanswered_question_reverifications_question_faq UNIQUE (question_id, faq_id)
);

CREATE INDEX idx_unanswered_question_reverifications_faq_id ON unanswered_question_reverifications (faq_id);
