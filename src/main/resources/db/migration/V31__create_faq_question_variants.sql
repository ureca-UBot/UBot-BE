ALTER TABLE faq ADD COLUMN cacheable BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE faq_question_variants (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_faq_id BIGINT    NOT NULL REFERENCES faq (id) ON DELETE CASCADE,
    question      TEXT      NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at    TIMESTAMP
);

CREATE INDEX idx_faq_question_variants_origin_faq_id ON faq_question_variants (origin_faq_id);

INSERT INTO faq_question_variants (origin_faq_id, question, created_at, updated_at, deleted_at)
SELECT id, question, created_at, updated_at, deleted_at
FROM faq;

ALTER TABLE faq_embeddings ADD COLUMN faq_question_variant_id BIGINT;

UPDATE faq_embeddings fe
SET faq_question_variant_id = v.id
FROM faq_question_variants v
WHERE v.origin_faq_id = fe.faq_id;

ALTER TABLE faq_embeddings
    ALTER COLUMN faq_question_variant_id SET NOT NULL,
    DROP CONSTRAINT faq_embeddings_pkey,
    DROP COLUMN faq_id,
    ADD CONSTRAINT faq_embeddings_faq_question_variant_id_fkey
        FOREIGN KEY (faq_question_variant_id) REFERENCES faq_question_variants (id) ON DELETE CASCADE,
    ADD PRIMARY KEY (faq_question_variant_id, profile_id, vector_type);
