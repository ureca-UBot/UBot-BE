-- 상품 카탈로그 확장: 인터넷/IPTV, 결합 회선 수, 요금제 포함 부가서비스, 상품 분류
CREATE TABLE home_products (
    home_product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL UNIQUE,
    name            VARCHAR(150) NOT NULL,
    description     TEXT,
    product_type    VARCHAR(20)  NOT NULL CHECK (product_type IN ('INTERNET', 'IPTV')),
    speed_mbps      INTEGER      CHECK (speed_mbps > 0),
    monthly_fee     INTEGER      NOT NULL CHECK (monthly_fee >= 0),
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_by      BIGINT       REFERENCES users (user_id),
    updated_by      BIGINT       REFERENCES users (user_id),
    deleted_at      TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_home_products_speed CHECK (
        (product_type = 'INTERNET' AND speed_mbps IS NOT NULL)
        OR (product_type = 'IPTV' AND speed_mbps IS NULL)
    )
);

-- 결합은 할인 단계마다 별도 상품이다(가족 2~5인, 친구 2·3인, 홈 100/500/기가 등).
-- line_count는 결합에 묶는 회선 수이고, NULL이면 회선 수 제한이 없다(가족 오래함께: 2회선 이상).
-- home_product_id는 홈 결합에 필요한 인터넷 상품이다.
ALTER TABLE bundle_products
    ADD COLUMN bundle_type VARCHAR(20) NOT NULL DEFAULT 'ETC'
        CHECK (bundle_type IN ('FAMILY', 'HOME', 'DUO', 'ETC')),
    ADD COLUMN line_count INTEGER CHECK (line_count BETWEEN 1 AND 10),
    ADD COLUMN home_product_id BIGINT REFERENCES home_products (home_product_id) ON DELETE SET NULL;

CREATE INDEX idx_bundle_products_home_product ON bundle_products (home_product_id);

ALTER TABLE addon_services
    ADD COLUMN category VARCHAR(30) NOT NULL DEFAULT 'ETC'
        CHECK (category IN ('DATA_CHARGE', 'VOICE_CHARGE', 'CONTENT', 'SAFETY', 'CALL', 'BLOCKING', 'ETC'));

CREATE TABLE plan_included_addons (
    plan_id          BIGINT    NOT NULL REFERENCES plans (plan_id) ON DELETE CASCADE,
    addon_service_id BIGINT    NOT NULL REFERENCES addon_services (addon_service_id) ON DELETE CASCADE,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (plan_id, addon_service_id)
);

CREATE INDEX idx_plan_included_addons_addon ON plan_included_addons (addon_service_id);

-- 사용자 가입: 요금제 변경 월 1회 제한
ALTER TABLE subscriptions ADD COLUMN plan_changed_at TIMESTAMP;

-- 인터넷/IPTV 가입. 종류별로 하나만 이용한다.
-- 회원 정리(purge)는 휴대폰 회선만 보존 대상으로 보므로, 회원이 지워지면 함께 지운다.
CREATE TABLE home_subscriptions (
    home_subscription_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    home_product_id       BIGINT       NOT NULL REFERENCES home_products (home_product_id),
    product_type          VARCHAR(20)  NOT NULL CHECK (product_type IN ('INTERNET', 'IPTV')),
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ENDED')),
    joined_at             TIMESTAMP    NOT NULL,
    ended_at              TIMESTAMP,
    product_name_snapshot VARCHAR(150) NOT NULL CHECK (length(trim(product_name_snapshot)) > 0),
    monthly_fee_snapshot  INTEGER      NOT NULL CHECK (monthly_fee_snapshot >= 0),
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_home_subscriptions_termination CHECK (
        (status = 'ENDED' AND ended_at IS NOT NULL AND ended_at >= joined_at)
        OR (status = 'ACTIVE' AND ended_at IS NULL)
    )
);

CREATE UNIQUE INDEX uq_home_subscriptions_active_type
    ON home_subscriptions (user_id, product_type) WHERE status = 'ACTIVE';
CREATE INDEX idx_home_subscriptions_product ON home_subscriptions (home_product_id);

-- 결합 그룹. 결합 상품은 구성 회선의 subscription_bundles에서 읽는다.
-- 상품·회선 정리(purge)를 막지 않도록 상품 FK를 두지 않고, 대표 회선이 지워지면 비운다.
CREATE TABLE bundle_groups (
    bundle_group_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    representative_subscription_id BIGINT      REFERENCES subscriptions (subscription_id) ON DELETE SET NULL,
    status                         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ENDED')),
    ended_at                       TIMESTAMP,
    created_at                     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bundle_groups_termination CHECK (
        (status = 'ENDED' AND ended_at IS NOT NULL)
        OR (status = 'ACTIVE' AND ended_at IS NULL AND representative_subscription_id IS NOT NULL)
    )
);

CREATE INDEX idx_bundle_groups_representative ON bundle_groups (representative_subscription_id);

ALTER TABLE subscription_bundles
    ADD COLUMN bundle_group_id BIGINT REFERENCES bundle_groups (bundle_group_id) ON DELETE SET NULL;

CREATE INDEX idx_subscription_bundles_group_status ON subscription_bundles (bundle_group_id, status);

-- 부가서비스 가입 경로. 요금제를 바꾸면 이전 요금제로 들어온 PLAN_INCLUDED 행만 해지한다.
-- 요금제 포함 목록이 나중에 바뀌어도 가입 당시 행으로 판단하므로 plan_included_addons로 추측하지 않는다.
ALTER TABLE subscription_addons
    ADD COLUMN source VARCHAR(20) NOT NULL DEFAULT 'SUBSCRIBED'
        CHECK (source IN ('SUBSCRIBED', 'PLAN_INCLUDED'));
