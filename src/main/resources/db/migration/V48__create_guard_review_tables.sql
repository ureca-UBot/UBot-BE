CREATE TABLE guard_review_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('ANALYSIS','VALIDATION')),
    analysis_mode VARCHAR(16),
    status VARCHAR(16) NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED','RUNNING','COMPLETED','FAILED')),
    processed INTEGER NOT NULL DEFAULT 0,
    total INTEGER NOT NULL DEFAULT 0,
    cutoff TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    requested_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    request JSONB NOT NULL DEFAULT '{}',
    result JSONB NOT NULL DEFAULT '{}',
    lease_token UUID,
    lease_until TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details_retained BOOLEAN NOT NULL DEFAULT true,
    CHECK ((kind='ANALYSIS' AND analysis_mode IS NOT NULL AND analysis_mode IN ('INCREMENTAL','FULL'))
        OR (kind='VALIDATION' AND analysis_mode IS NULL))
);
CREATE INDEX idx_guard_review_runs_pending ON guard_review_runs(status, created_at);

CREATE TABLE guard_review_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES guard_review_runs(id) ON DELETE CASCADE,
    source_id BIGINT REFERENCES answer_attempts_history(attempt_id) ON DELETE SET NULL,
    source_key VARCHAR(200) NOT NULL,
    source_fingerprint VARCHAR(64) NOT NULL,
    question_snapshot TEXT,
    answer_snapshot TEXT,
    finished_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','COMPLETED','FAILED')),
    error_code VARCHAR(64),
    UNIQUE(run_id, source_key)
);
CREATE INDEX idx_guard_review_items_pending ON guard_review_items(run_id,id) WHERE status='PENDING';
CREATE INDEX idx_guard_review_items_checkpoint ON guard_review_items(source_key,finished_at DESC,id DESC)
    WHERE status='COMPLETED';

CREATE TABLE guard_review_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('WORD','WARNING')),
    category VARCHAR(64) NOT NULL,
    expression VARCHAR(2000) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    intent VARCHAR(32) NOT NULL,
    normalized_hash VARCHAR(64) NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','REJECTED','APPLIED','DISABLED','REVIEWED')),
    word_id BIGINT REFERENCES forbidden_words(id) ON DELETE SET NULL,
    embedding_profile VARCHAR(200),
    embedding vector(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (kind <> 'WARNING' OR (word_id IS NULL AND status NOT IN ('APPLIED','DISABLED'))),
    UNIQUE(kind, category, intent, normalized_hash)
);

CREATE TABLE guard_review_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL REFERENCES guard_review_candidates(id),
    first_run_id BIGINT NOT NULL REFERENCES guard_review_runs(id),
    source_id BIGINT REFERENCES answer_attempts_history(attempt_id) ON DELETE SET NULL,
    source_key VARCHAR(200) NOT NULL,
    source_fingerprint VARCHAR(64) NOT NULL,
    stage VARCHAR(16) NOT NULL CHECK (stage IN ('INPUT','OUTPUT','COUNSEL')),
    category VARCHAR(64) NOT NULL,
    notified_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(candidate_id, source_key, source_fingerprint, stage, category)
);
CREATE UNIQUE INDEX uq_guard_review_candidates_word_expression ON guard_review_candidates(normalized_hash) WHERE kind='WORD';
CREATE INDEX idx_guard_review_findings_candidate ON guard_review_findings(candidate_id, id);
CREATE INDEX idx_guard_review_findings_source ON guard_review_findings(source_key,source_fingerprint,stage,category);

CREATE TABLE guard_review_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL REFERENCES guard_review_candidates(id),
    revision BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    admin_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    expression VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_guard_review_history_latest ON guard_review_history(candidate_id,action,id DESC);

