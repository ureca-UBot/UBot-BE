CREATE TABLE surging_clusters (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region               VARCHAR(30)  NOT NULL,
    representative_question TEXT      NOT NULL,
    embedding_profile_id BIGINT       NOT NULL REFERENCES embedding_profiles (profile_id),
    centroid_embedding   vector(1024) NOT NULL,
    alerted_at           TIMESTAMP,
    last_occurred_at     TIMESTAMP    NOT NULL,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_surging_clusters_region_profile
    ON surging_clusters (region, embedding_profile_id, last_occurred_at DESC);

CREATE TABLE surging_questions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_log_id BIGINT    NOT NULL UNIQUE REFERENCES question_log (id) ON DELETE CASCADE,
    cluster_id      BIGINT    NOT NULL REFERENCES surging_clusters (id),
    occurred_at     TIMESTAMP NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_surging_questions_cluster_occurred_at
    ON surging_questions (cluster_id, occurred_at);

CREATE TABLE surging_question_embeddings (
    question_id          BIGINT       NOT NULL REFERENCES surging_questions (id) ON DELETE CASCADE,
    embedding_profile_id BIGINT       NOT NULL REFERENCES embedding_profiles (profile_id),
    vector               vector(1024) NOT NULL,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (question_id, embedding_profile_id)
);

CREATE TABLE surging_alerts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region         VARCHAR(30) NOT NULL,
    subject        VARCHAR(200),
    question_snapshots JSONB   NOT NULL,
    question_count INTEGER     NOT NULL CHECK (question_count > 0),
    window_minutes INTEGER     NOT NULL CHECK (window_minutes > 0),
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PROCESSED')),
    updated_by     BIGINT      REFERENCES users (user_id) ON DELETE SET NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_surging_alerts_status_created_at
    ON surging_alerts (status, created_at DESC, id DESC);

ALTER TABLE outbox_events
    DROP CONSTRAINT outbox_events_event_type_check,
    ADD CONSTRAINT outbox_events_event_type_check CHECK (event_type IN (
        'UNANSWERED_QUESTION', 'FAQ_REVERIFY', 'SURGING_QUESTION', 'SURGING_ALERT_LABEL'
    ));

ALTER TABLE notifications
    ADD COLUMN surging_alert_id BIGINT REFERENCES surging_alerts (id) ON DELETE CASCADE;

ALTER TABLE notifications
    DROP CONSTRAINT notifications_type_check,
    ADD CONSTRAINT notifications_type_check CHECK (type IN (
        'RESERVATION_CONFIRMED', 'RESERVATION_CANCELED', 'RESERVATION_REMINDER',
        'BILLING_DUE_SOON', 'BILLING_OVERDUE',
        'ROAMING_START', 'ROAMING_END',
        'CONTRACT_EXPIRING', 'INSTALLMENT_EXPIRING',
        'DATA_USAGE_THRESHOLD', 'SURGING_ALERT'
    ));

CREATE INDEX idx_notifications_surging_alert_id
    ON notifications (surging_alert_id)
    WHERE surging_alert_id IS NOT NULL;
