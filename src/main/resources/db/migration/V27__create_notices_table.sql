CREATE TABLE notices (
    notice_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(20)  NOT NULL CHECK (type IN ('NOTICE', 'OUTAGE')),
    title         VARCHAR(100) NOT NULL,
    content       TEXT         NOT NULL,
    target_region VARCHAR(20),
    ends_at       TIMESTAMP,
    created_by    BIGINT       REFERENCES users (user_id),
    updated_by    BIGINT       REFERENCES users (user_id),
    deleted_at    TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notices_created_at ON notices (created_at DESC, notice_id DESC) WHERE deleted_at IS NULL;
CREATE INDEX idx_notices_type_ends_at ON notices (type, ends_at) WHERE deleted_at IS NULL;
