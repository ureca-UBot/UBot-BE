-- FAQ 수정·삭제와 독립적으로 선택 시점의 서버 원문을 대화에 보존한다.
CREATE TABLE public.conversation_faq_selections (
    selection_id uuid PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES public.conversations(conversation_id) ON DELETE CASCADE,
    faq_id bigint NOT NULL,
    question text NOT NULL,
    answer text NOT NULL,
    created_at timestamp NOT NULL DEFAULT localtimestamp
);
CREATE INDEX ix_conversation_faq_selections_history
    ON public.conversation_faq_selections(conversation_id,created_at,selection_id);

CREATE SCHEMA counseling;

CREATE TABLE counseling.sessions (
    id UUID PRIMARY KEY,
    customer_id BIGINT NOT NULL CONSTRAINT fk_sessions_customer REFERENCES public.users(user_id) ON DELETE CASCADE,
    counselor_id BIGINT CONSTRAINT fk_sessions_counselor REFERENCES public.users(user_id) ON DELETE SET NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('WAITING','ACTIVE','PAUSED','ENDED')),
    assignment_version BIGINT NOT NULL DEFAULT 0,
    last_delivered_seq BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    waiting_since TIMESTAMPTZ NOT NULL DEFAULT now(),
    paused_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    conversation_id UUID NOT NULL CONSTRAINT fk_sessions_conversation REFERENCES public.conversations(public_id) ON DELETE CASCADE,
    handoff_id UUID,
    CHECK (status NOT IN ('ACTIVE','PAUSED') OR counselor_id IS NOT NULL)
);
CREATE UNIQUE INDEX uq_sessions_open_customer ON counseling.sessions(customer_id) WHERE status <> 'ENDED';
CREATE UNIQUE INDEX uq_sessions_busy_counselor ON counseling.sessions(counselor_id) WHERE status IN ('ACTIVE','PAUSED');
CREATE INDEX idx_sessions_waiting_since ON counseling.sessions(waiting_since, id) WHERE status = 'WAITING';
CREATE UNIQUE INDEX uq_sessions_handoff_id ON counseling.sessions(handoff_id) WHERE handoff_id IS NOT NULL;
CREATE INDEX idx_sessions_customer_conversation ON counseling.sessions(customer_id,conversation_id,created_at DESC);
CREATE INDEX idx_sessions_conversation ON counseling.sessions(conversation_id, created_at, id);

CREATE TABLE counseling.counselor_presence (
    user_id BIGINT PRIMARY KEY CONSTRAINT fk_counselor_presence_user REFERENCES public.users(user_id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('AVAILABLE','OFFLINE')),
    last_heartbeat_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE counseling.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL CONSTRAINT fk_messages_session REFERENCES counseling.sessions(id) ON DELETE CASCADE,
    sender_id BIGINT CONSTRAINT fk_messages_sender REFERENCES public.users(user_id) ON DELETE SET NULL,
    sender_role VARCHAR(16) NOT NULL,
    assignment_version BIGINT NOT NULL,
    client_message_id UUID NOT NULL,
    content VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','ALLOWED','BLOCKED','CHECK_FAILED')),
    delivery_sequence BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ,
    CONSTRAINT uq_messages_sender_client_message UNIQUE (session_id, sender_id, client_message_id),
    CONSTRAINT uq_messages_delivery_sequence UNIQUE (session_id, delivery_sequence),
    CHECK ((status = 'ALLOWED') = (delivery_sequence IS NOT NULL)),
    CHECK ((status = 'PENDING') = (decided_at IS NULL))
);
CREATE INDEX idx_messages_pending_created_at ON counseling.messages(created_at) WHERE status = 'PENDING';
CREATE INDEX idx_messages_session_delivery_sequence ON counseling.messages(session_id, delivery_sequence) WHERE status = 'ALLOWED';
CREATE INDEX idx_messages_rejected_created_at ON counseling.messages(created_at) WHERE status IN ('BLOCKED', 'CHECK_FAILED');

CREATE TABLE counseling.guard_profiles (
    profile_version VARCHAR(64) PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    preprocessing_version VARCHAR(32) NOT NULL,
    dataset_sha256 VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE counseling.guard_config_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    profile_version VARCHAR(64) NOT NULL,
    rule_version VARCHAR(32) NOT NULL,
    threshold DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE counseling.safety_filter_vectors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(16) NOT NULL CHECK (category = 'INSULT'),
    example_text VARCHAR(1000) NOT NULL,
    embedding public.vector(1024) NOT NULL,
    severity SMALLINT NOT NULL CHECK (severity BETWEEN 1 AND 3),
    model_name VARCHAR(100) NOT NULL,
    profile_version VARCHAR(64) NOT NULL REFERENCES counseling.guard_profiles(profile_version),
    active BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX idx_safety_filter_vectors_profile_model ON counseling.safety_filter_vectors(profile_version, model_name) WHERE active;
CREATE TABLE counseling.safety_filter_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL CONSTRAINT uq_safety_filter_events_message UNIQUE
        CONSTRAINT fk_safety_events_message REFERENCES counseling.messages(id) ON DELETE CASCADE,
    decision VARCHAR(16) NOT NULL CHECK (decision IN ('ALLOWED','BLOCKED','CHECK_FAILED')),
    matched_vector_id BIGINT REFERENCES counseling.safety_filter_vectors(id),
    score DOUBLE PRECISION,
    threshold DOUBLE PRECISION NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    profile_version VARCHAR(64) NOT NULL,
    rule_version VARCHAR(32) NOT NULL,
    category VARCHAR(16),
    error_code VARCHAR(64),
    admin_review VARCHAR(32) CHECK (admin_review IN ('FALSE_POSITIVE','TRUE_POSITIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_safety_filter_events_created_at ON counseling.safety_filter_events(created_at DESC, id DESC);
CREATE TABLE counseling.role_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT CONSTRAINT fk_role_audit_admin REFERENCES public.users(user_id) ON DELETE SET NULL,
    user_id BIGINT CONSTRAINT fk_role_audit_user REFERENCES public.users(user_id) ON DELETE SET NULL,
    previous_role VARCHAR(16) NOT NULL,
    new_role VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE counseling.rate_buckets (
    user_id BIGINT PRIMARY KEY CONSTRAINT fk_rate_buckets_user REFERENCES public.users(user_id) ON DELETE CASCADE,
    window_start TIMESTAMPTZ NOT NULL DEFAULT now(),
    requests INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE counseling.safety_sentences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_version VARCHAR(64) NOT NULL REFERENCES counseling.guard_profiles(profile_version),
    model_name VARCHAR(100) NOT NULL,
    content VARCHAR(1000) NOT NULL,
    normalized_sha256 VARCHAR(64) NOT NULL,
    severity SMALLINT NOT NULL CHECK (severity BETWEEN 1 AND 3),
    enabled BOOLEAN NOT NULL DEFAULT true,
    revision BIGINT NOT NULL DEFAULT 1,
    indexed_revision BIGINT,
    indexed_vector_id BIGINT UNIQUE REFERENCES counseling.safety_filter_vectors(id),
    index_token UUID,
    index_started_at TIMESTAMPTZ,
    index_error VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK ((indexed_revision IS NULL) = (indexed_vector_id IS NULL)),
    CHECK ((index_token IS NULL) = (index_started_at IS NULL))
);
CREATE UNIQUE INDEX uq_safety_sentences_profile_text
    ON counseling.safety_sentences(profile_version, model_name, normalized_sha256) WHERE deleted_at IS NULL;
CREATE INDEX idx_safety_sentences_profile_id
    ON counseling.safety_sentences(profile_version, model_name, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE counseling.safety_sentence_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_id BIGINT NOT NULL REFERENCES counseling.safety_sentences(id),
    admin_id BIGINT CONSTRAINT fk_safety_sentence_audit_admin REFERENCES public.users(user_id) ON DELETE SET NULL,
    action VARCHAR(24) NOT NULL CHECK (action IN ('SEED','CREATE','UPDATE','DELETE','INDEX_REQUESTED','INDEXED','INDEX_FAILED')),
    revision BIGINT NOT NULL,
    content VARCHAR(1000) NOT NULL,
    severity SMALLINT NOT NULL,
    enabled BOOLEAN NOT NULL,
    vector_id BIGINT REFERENCES counseling.safety_filter_vectors(id),
    error_code VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_safety_sentence_audit_sentence_id ON counseling.safety_sentence_audit(sentence_id, id);

CREATE TABLE counseling.session_history (
    session_id UUID NOT NULL CONSTRAINT fk_session_history_session REFERENCES counseling.sessions(id) ON DELETE CASCADE,
    sequence BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER','AI','COUNSELOR')),
    content TEXT NOT NULL,
    source VARCHAR(16) NOT NULL CHECK (source IN ('SAVED','SCREEN','COUNSEL')),
    origin_session_id UUID,
    origin_sequence BIGINT,
    PRIMARY KEY (session_id,sequence)
);
