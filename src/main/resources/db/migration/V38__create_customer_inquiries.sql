CREATE TABLE customer_inquiries (
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    content VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED', 'RESOLVED')),
    admin_reply VARCHAR(1000),
    resolved_by BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    CONSTRAINT customer_inquiries_reply_state_check CHECK (
        (status = 'RECEIVED' AND admin_reply IS NULL AND resolved_at IS NULL AND resolved_by IS NULL)
        OR (status = 'RESOLVED' AND admin_reply IS NOT NULL AND resolved_at IS NOT NULL)
    ),
    CONSTRAINT customer_inquiries_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT customer_inquiries_content_not_blank CHECK (length(btrim(content)) > 0)
);

CREATE INDEX idx_customer_inquiries_user_created ON customer_inquiries (user_id, created_at DESC, inquiry_id DESC);
CREATE INDEX idx_customer_inquiries_status_created ON customer_inquiries (status, created_at DESC, inquiry_id DESC);
CREATE INDEX idx_customer_inquiries_created ON customer_inquiries (created_at DESC, inquiry_id DESC);
