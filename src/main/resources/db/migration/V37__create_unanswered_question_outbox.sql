CREATE TABLE unanswered_question_outbox (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id         BIGINT           NOT NULL REFERENCES answer_attempts_history (attempt_id) ON DELETE CASCADE,
    sub_question_index INTEGER          NOT NULL CHECK (sub_question_index >= 1),
    sub_question       TEXT             NOT NULL,
    user_text          TEXT             NOT NULL,
    reason             VARCHAR(20)      NOT NULL CHECK (reason IN ('NO_FAQ', 'INSUFFICIENT_FAQ', 'LLM_ABSTAIN')),
    best_faq_id        BIGINT           REFERENCES faq (id) ON DELETE SET NULL,
    best_similarity    DOUBLE PRECISION,
    retry_count        INTEGER          NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    created_at         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_unanswered_question_outbox_attempt_sub_question UNIQUE (attempt_id, sub_question_index)
);
