CREATE TABLE chat_jobs (
    job_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id       BIGINT      NOT NULL REFERENCES answer_attempts_history (attempt_id) ON DELETE CASCADE,
    execution_status VARCHAR(20) NOT NULL DEFAULT 'QUEUED'
                     CHECK (execution_status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    created_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at       TIMESTAMP,
    finished_at      TIMESTAMP,
    CONSTRAINT uq_chat_jobs_attempt_id UNIQUE (attempt_id)
);

CREATE INDEX idx_chat_jobs_execution_status_created_at ON chat_jobs (execution_status, created_at);
