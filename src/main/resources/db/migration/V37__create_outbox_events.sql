CREATE TABLE outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type      VARCHAR(50)  NOT NULL CHECK (event_type IN ('UNANSWERED_QUESTION')),
    dedup_key       VARCHAR(200) NOT NULL,
    payload         JSONB        NOT NULL,
    retry_count     INTEGER      NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    next_attempt_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_outbox_events_dedup_key UNIQUE (dedup_key)
);

CREATE INDEX idx_outbox_events_next_attempt_at ON outbox_events (next_attempt_at);
